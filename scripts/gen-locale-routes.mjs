#!/usr/bin/env node
/**
 * gen-locale-routes.mjs — writes the prefixed copy of every page.
 *
 * Each page and layout under src/app gets a thin twin under
 * src/app/[locale]/ that re-exports it, so /ja/about/, /zh-cn/journals/ ...
 * render the same page with the interface in that language (the language
 * comes from the address; see src/components/I18n.tsx). Page source is
 * never duplicated.
 *
 * Not copied: the per-record pages in EXCLUDED (~1,500 pages; copying them
 * into four languages would break Cloudflare Pages' 20,000-file limit).
 * Keep EXCLUDED in step with UNLOCALIZED_PATTERNS in src/lib/i18n/locales.ts.
 *
 *   node scripts/gen-locale-routes.mjs          write the copies
 *   node scripts/gen-locale-routes.mjs --check  fail if they are out of date
 *
 * Run it after adding, moving or removing a page.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs'
import { dirname, join, relative, sep } from 'path'

const APP = 'src/app'
const OUT = join(APP, '[locale]')
// Route directories (relative to src/app) whose pages are not copied.
export const EXCLUDED = ['journal/[code]', 'publishers/[slug]', 'rankings/edition/[year]/[code]']
// Written by hand: the home page, translated in full, and the [locale] layout.
const HAND_WRITTEN = new Set(['page.tsx', 'layout.tsx'])
const MARK = '// Generated by scripts/gen-locale-routes.mjs; do not edit.'

function routeFiles(dir) {
  const out = []
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) { if (p !== OUT) out.push(...routeFiles(p)) }
    else if (e.name === 'page.tsx' || e.name === 'layout.tsx') out.push(relative(APP, p).split(sep).join('/'))
  }
  return out
}

function twin(file) {
  const src = readFileSync(join(APP, file), 'utf8')
  const has = name => new RegExp(`^export (async )?(function|const) ${name}\\b`, 'm').test(src)
  const mod = `@/app/${file.replace(/\.tsx$/, '')}`
  const names = ['metadata', 'generateMetadata', 'generateStaticParams', 'viewport', 'generateViewport'].filter(has)
  const lines = [MARK, `// Re-exports src/app/${file} under each language prefix.`]
  lines.push(`export { default${names.map(n => `, ${n}`).join('')} } from '${mod}'`)
  // Route segment config must be a literal in the route file itself.
  for (const m of src.matchAll(/^export const (dynamic|dynamicParams|revalidate|fetchCache|runtime|preferredRegion|maxDuration) = .+$/gm)) lines.push(m[0])
  return lines.join('\n') + '\n'
}

const wanted = new Map()
for (const file of routeFiles(APP)) {
  if (HAND_WRITTEN.has(file)) continue
  const dir = dirname(file)
  if (EXCLUDED.some(x => dir === x || dir.startsWith(x + '/'))) continue
  wanted.set(join(OUT, file), twin(file))
}

const existing = existsSync(OUT) ? routeFiles(OUT).map(f => join(APP, f)).filter(p => readFileSync(p, 'utf8').startsWith(MARK)) : []
const check = process.argv.includes('--check')
const stale = [
  ...[...wanted].filter(([p, body]) => !existsSync(p) || readFileSync(p, 'utf8') !== body).map(([p]) => p),
  ...existing.filter(p => !wanted.has(p)),
]
if (check) {
  if (stale.length) { console.error(`gen-locale-routes: out of date, run node scripts/gen-locale-routes.mjs:\n  ${stale.join('\n  ')}`); process.exit(1) }
  console.log(`gen-locale-routes: ${wanted.size} localized routes up to date`)
} else {
  for (const p of existing) if (!wanted.has(p)) rmSync(p)
  for (const [p, body] of wanted) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body) }
  // Drop directories left empty by removed pages.
  const prune = d => { for (const e of readdirSync(d, { withFileTypes: true })) if (e.isDirectory()) prune(join(d, e.name)); if (d !== OUT && !readdirSync(d).length) rmSync(d, { recursive: true }) }
  prune(OUT)
  console.log(`gen-locale-routes: wrote ${wanted.size} localized routes`)
}
